"""
modules/llm.py

Сервіс для розпізнавання музейних експонатів і картин через Gemini Vision API.
Повертає структурований JSON-об'єкт з інформацією про експонат.
"""

import os
import json
import re
from dotenv import load_dotenv

load_dotenv()

from google import genai
from google.genai import types
from PIL import Image

# ---------------------------------------------------------------------------
# Конфігурація
# ---------------------------------------------------------------------------

client = genai.Client(api_key=os.environ["GEMINI_API_KEY"])

MODEL_NAME = "gemini-2.5-flash"

# Виняток для нерелевантних зображень
class NotAnExhibitError(Exception):
    pass

# ---------------------------------------------------------------------------
# Схема через types.Schema
# ---------------------------------------------------------------------------

def _build_schema() -> types.Schema:
    T = types.Type
    s = types.Schema

    return s(
        type=T.OBJECT,
        properties={
            "is_exhibit": s(
                type=T.BOOLEAN,
                description=(
                    "true — якщо на фото музейний експонат, картина, скульптура, "
                    "архітектурна пам'ятка або будь-який культурний об'єкт. "
                    "false — якщо це звичайна побутова сцена, селфі, їжа, тварина тощо."
                ),
            ),
            "назва": s(type=T.STRING, description="Назва експоната або картини"),
            "автор_або_культура": s(type=T.STRING, description="Автор або культура/цивілізація. Якщо невідомо — 'Невідомо'."),
            "період": s(type=T.STRING, description="Приблизна дата або епоха, наприклад '1889' або 'XV ст.'"),
            "тип_експоната": s(
                type=T.STRING,
                enum=["картина", "скульптура", "артефакт", "документ", "зброя", "ювелірний виріб", "побутовий предмет", "архітектура", "інше"],
            ),
            "цікаві_факти": s(
                type=T.ARRAY,
                items=s(type=T.STRING),
                description="2–4 найцікавіших факти для відвідувача музею",
            ),
            "матеріал_або_техніка": s(type=T.STRING, description="З чого зроблено або яка техніка виконання"),
            "де_зберігається": s(type=T.STRING, description="Музей або місце зберігання. Якщо невідомо — 'Невідомо'."),
            "екскурсійний_опис": s(type=T.STRING, description="Живий опис у 2–3 реченнях, як від екскурсовода"),
        },
        required=[
            "is_exhibit",
            "назва",
            "автор_або_культура",
            "період",
            "тип_експоната",
            "цікаві_факти",
            "матеріал_або_техніка",
            "де_зберігається",
            "екскурсійний_опис",
        ],
    )


# ---------------------------------------------------------------------------
# Системний промпт
# ---------------------------------------------------------------------------

SYSTEM_PROMPT = """Ти — досвідчений музейний гід і мистецтвознавець.
Твоє завдання — розпізнати музейний експонат або картину на фотографії
та надати відповідь ВИКЛЮЧНО у форматі JSON згідно із заданою схемою.

Правила:
- Спочатку визнач: чи є це музейним експонатом, картиною, скульптурою або архітектурною пам'яткою?
- Якщо НІ (наприклад, звичайне фото людини, їжі, тварини, побутової сцени) — постав is_exhibit: false, решту полів заповни порожніми рядками або порожніми масивами.
- Якщо ТАК — постав is_exhibit: true і заповни всі поля.
- Відповідай ТІЛЬКИ українською мовою.
- Якщо на фото — картина, заповни поле "автор_або_культура" як автора.
- Якщо це артефакт чи предмет — вкажи культуру або цивілізацію.
- Цікаві факти мають бути справді захоплюючими, не банальними.
- Екскурсійний опис пиши живо, як справжній гід, що говорить з відвідувачем.
- Якщо щось невідомо з фото — чесно вкажи "Невідомо" або зроби обґрунтоване припущення.
- Не додавай жодного тексту поза JSON.
"""

# ---------------------------------------------------------------------------
# Основна функція
# ---------------------------------------------------------------------------

def analyze_exhibit(image: Image.Image) -> dict:
    """
    Аналізує зображення музейного експоната або картини.

    Returns:
        dict із полями згідно схеми

    Raises:
        NotAnExhibitError: якщо на фото не музейний експонат
        ValueError: якщо Gemini повернув некоректний JSON
        RuntimeError: якщо API повернув помилку
    """
    user_prompt = (
        "Розпізнай цей музейний експонат або картину. "
        "Поверни відповідь суворо у форматі JSON згідно схеми."
    )

    try:
        response = client.models.generate_content(
            model=MODEL_NAME,
            contents=[user_prompt, image],
            config=types.GenerateContentConfig(
                system_instruction=SYSTEM_PROMPT,
                response_mime_type="application/json",
                response_schema=_build_schema(),
                temperature=0.4,
                max_output_tokens=4096,
            ),
        )
    except Exception as e:
        raise RuntimeError(f"Gemini API error: {e}") from e

    raw_text = response.text.strip()
    raw_text = re.sub(r"^```(?:json)?\s*", "", raw_text)
    raw_text = re.sub(r"\s*```$", "", raw_text)

    try:
        result = json.loads(raw_text)
    except json.JSONDecodeError as e:
        raise ValueError(f"Gemini повернув не-JSON відповідь: {raw_text[:300]}") from e

    # Перевірка релевантності
    if not result.get("is_exhibit", True):
        raise NotAnExhibitError(
            "На фото не схоже на музейний експонат, картину або архітектурну пам'ятку. "
            "Будь ласка, завантажте фото музейного експоната, картини або архітектурної споруди."
        )

    _validate(result)
    return result


# ---------------------------------------------------------------------------
# Валідація обов'язкових полів
# ---------------------------------------------------------------------------

def _validate(data: dict) -> None:
    required = ["назва", "автор_або_культура", "період", "тип_експоната",
                "цікаві_факти", "матеріал_або_техніка", "де_зберігається", "екскурсійний_опис"]
    missing = [f for f in required if f not in data]
    if missing:
        raise ValueError(f"JSON відповідь не містить обов'язкових полів: {missing}")


# ---------------------------------------------------------------------------
# Форматування для Gradio / TTS
# ---------------------------------------------------------------------------

def format_for_display(data: dict) -> str:
    facts = "\n".join(f"  • {f}" for f in data.get("цікаві_факти", []))
    return f"""🏛️ {data['назва']}

👤 Автор / культура: {data['автор_або_культура']}
📅 Період: {data['період']}
🎨 Тип: {data['тип_експоната']}
🔧 Матеріал / техніка: {data['матеріал_або_техніка']}
📍 Де зберігається: {data['де_зберігається']}

✨ Цікаві факти:
{facts}

🎙️ Екскурсовод:
{data['екскурсійний_опис']}
"""


def format_for_tts(data: dict) -> str:
    facts = ". ".join(data.get("цікаві_факти", []))
    return (
        f"{data['назва']}. "
        f"Автор або культура: {data['автор_або_культура']}. "
        f"Період: {data['період']}. "
        f"{facts}. "
        f"{data['екскурсійний_опис']}"
    )


if __name__ == "__main__":
    image_path = "../examples/1.jpg"  # <- змінити на свій файл

    image = Image.open(image_path)
    data = analyze_exhibit(image)
    print(format_for_display(data))
    print("─" * 40)
    print(format_for_tts(data))